CREATE TABLE IF NOT EXISTS runs (id TEXT PRIMARY KEY, round INTEGER NOT NULL, ip TEXT NOT NULL, t0 INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS runs_ip ON runs (ip, t0);
CREATE TABLE IF NOT EXISTS scores (
  id INTEGER PRIMARY KEY AUTOINCREMENT, round INTEGER NOT NULL, pid TEXT NOT NULL, name TEXT NOT NULL, score INTEGER NOT NULL,
  seeds INTEGER NOT NULL, dist_m INTEGER NOT NULL, stomps INTEGER NOT NULL, char TEXT NOT NULL, upg INTEGER NOT NULL, ts INTEGER NOT NULL, ip TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS scores_round ON scores (round, score DESC);
CREATE INDEX IF NOT EXISTS scores_ts ON scores (ts, score DESC);
CREATE INDEX IF NOT EXISTS scores_pid ON scores (pid, ts DESC);
